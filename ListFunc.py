
# USING APPEND FUNCTION
my_list1 = [10, 20, 30]
my_list1.append(50)
print("List after append:", my_list1)

# USING EXTEND()
my_list2= [1,2,3]
my_list2.extend([4,5,6,7])
print("List after extend:", my_list2)


# USING INSERT()
my_list3= [11,22,33,44]
my_list3.insert(3,66)
print("List after insert:", my_list3)


# USING REMOVE()
my_list4 = [10, 20, 30, 40]
my_list4.remove(20)
print("List after remove:", my_list4)


# USING POP()
my_list5 = [101,102,103,104,105,106]
my_list5.pop()
print("List after pop:", my_list5)